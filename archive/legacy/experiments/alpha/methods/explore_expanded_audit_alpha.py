"""Development-only value of 100 trusted blind labels for initial alpha.

Extra labels are generated by the synthetic true function and would require
trusted acquisition in deployment. They, local APIs, and saved proposals set
alpha; pooled evaluator scores are accessed only after candidate selection.
"""

import argparse
import csv
import json
from pathlib import Path

import numpy as np
import torch

from agent_client import AgentNode
from alpha_weight_experiments import run_stage3
from host_server import HostServer
from initial_alpha_methods import initial_alpha
from research_evaluation import load_evaluator_artifact, score_solution
from validation_calibrated_alpha import (CANDIDATE_METHODS,
                                         fit_residual_calibrator, select_candidate)


METHOD = "local_bias_risk_100"


def evaluate(roots, output):
    output = Path(output)
    if output.exists():
        raise FileExistsError(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    records = []
    for root_arg in roots:
        root = Path(root_arg)/"reference_clean"
        cohort = Path(root_arg).name
        candidates = {}
        for row in csv.DictReader((root/"candidate_rows.csv").open()):
            candidates[(int(row["seed"]), row["method"])] = row
        baselines = {int(row["seed"]):row for row in
                     csv.DictReader((root/"summary.csv").open())
                     if row["method"] == "validation_calibrated_multistart"}
        for item in map(json.loads, (root/"shared_costs.jsonl").read_text().splitlines()):
            seed = int(item["seed"])
            if seed not in baselines or "artifact_path" not in item:
                continue
            artifact = root/item["artifact_path"]
            payload = torch.load(artifact/"local_models.pt", map_location="cpu",
                                 weights_only=True)
            agents = []
            for ident in item["coalition_ids"]:
                agent = AgentNode(ident, None, n_features=payload["n_features"])
                agent.model.load_state_dict(payload["agents"][ident])
                agent.model.eval()
                agents.append(agent)
            original_x = np.asarray(item["blind_test_X"], float)
            original_y = np.asarray(item["blind_test_y"], float)
            audit = HostServer(0., payload["n_features"], test_seed=seed+7919,
                               n_test=100, constraint_mode="box_constrained")
            if not (np.array_equal(audit.test_X[:len(original_x)], original_x)
                    and np.array_equal(audit.test_y[:len(original_y)], original_y)):
                raise AssertionError(f"Expanded audit does not retain original labels: {cohort}/{seed}")
            proposals = np.asarray(item["proposals"], float)
            mse20 = json.loads(candidates[(seed,"B_stage0")]["stage0_mse"])
            alpha, alpha_audit = initial_alpha(
                "local_bias_risk", agents, mse20, audit.test_X, audit.test_y,
                proposals, 0.)
            server = HostServer(0., payload["n_features"], test_seed=seed+7919,
                                n_test=100, constraint_mode="box_constrained")
            server.trusted_agents = agents
            server.I_list = [np.asarray(v,float) for v in proposals]
            server.alphas = alpha.tolist()
            old = baselines[seed]
            record = {"cohort":cohort,"seed":seed,"method":METHOD,
                      "alpha":json.dumps(alpha.tolist()),
                      "alpha_audit":json.dumps(alpha_audit),
                      "trusted_labels_total":100,
                      "extra_trusted_labels":100-len(original_y),
                      "baseline_pooled":float(old["external_global_error"])}
            try:
                solution,_,_ = run_stage3(server,"best_of",30)
                violation = float(server.box_violation(solution))
                if violation > 1e-8:
                    raise ValueError(f"box violation {violation}")
                baseline_alpha = np.asarray(json.loads(
                    candidates[(seed,"B_stage0")]["initial_alpha"]),float)
                coefficients,_ = fit_residual_calibrator(
                    agents, original_x, original_y, baseline_alpha)
                solutions = {method:json.loads(candidates[(seed,method)]["final_solution"])
                             for method in CANDIDATE_METHODS}
                solutions[METHOD] = solution
                chosen,scores = select_candidate(
                    agents, baseline_alpha, coefficients, solutions, 0.,
                    method_order=CANDIDATE_METHODS+(METHOD,))
                evaluator = load_evaluator_artifact(artifact)[0]
                candidate_pooled = float(score_solution(evaluator, solution, 0.)[1])
                delivered_pooled = (candidate_pooled if chosen == METHOD
                                    else float(candidates[(seed,chosen)]["external_global_error"]))
                record.update({"status":"valid","solution":json.dumps(solution.tolist()),
                               "candidate_pooled":candidate_pooled,
                               "selected_extra":int(chosen==METHOD),
                               "selected_initialization":chosen,
                               "internal_score":scores[METHOD]["internal_target_error"],
                               "new_pooled":delivered_pooled,
                               "pooled_delta":delivered_pooled-record["baseline_pooled"]})
            except (ValueError,FloatingPointError) as exc:
                record.update({"status":"solver_failure","reason":str(exc)})
            records.append(record)
        print("completed",cohort,flush=True)
    fields=sorted({key for r in records for key in r})
    with output.open("w",newline="") as handle:
        writer=csv.DictWriter(handle,fieldnames=fields)
        writer.writeheader();writer.writerows(records)
    for cohort in sorted({r["cohort"] for r in records}):
        group=[r for r in records if r["cohort"]==cohort]
        valid=[r for r in group if r["status"]=="valid"]
        print(cohort,len(valid),"/",len(group),"mean_delta",
              float(np.mean([r["pooled_delta"] for r in valid])) if valid else None,
              "selected",sum(r.get("selected_extra",0) for r in valid),flush=True)


if __name__=="__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument("--roots",nargs="+",required=True)
    parser.add_argument("--output",required=True)
    args=parser.parse_args();evaluate(args.roots,args.output)
